SELECT id FROM pitikorana_seed_competences
ON CONFLICT (id) DO NOTHING;

WITH langues AS (
  SELECT code, id FROM langue WHERE code IN ('fr', 'mg')
), traductions AS (
  SELECT s.id AS id_competence, l.id AS id_langue,
    CASE l.code WHEN 'fr' THEN s.libelle_fr ELSE s.libelle_mg END AS libelle
  FROM pitikorana_seed_competences s CROSS JOIN langues l
)
INSERT INTO competence_traduction (id_competence, id_langue, libelle)
SELECT id_competence, id_langue, libelle FROM traductions
ON CONFLICT (id_competence, id_langue) DO UPDATE SET libelle = EXCLUDED.libelle;

-- Contrôles limités aux données de ce fichier.
SELECT count(*) AS competences_seed FROM pitikorana_seed_competences;
SELECT l.code, count(*) AS traductions_seed
FROM competence_traduction ct
JOIN pitikorana_seed_competences s ON s.id = ct.id_competence
JOIN langue l ON l.id = ct.id_langue
WHERE l.code IN ('fr', 'mg')
GROUP BY l.code ORDER BY l.code;
SELECT s.id AS competence_sans_fr_ou_mg
FROM pitikorana_seed_competences s
CROSS JOIN (SELECT id FROM langue WHERE code IN ('fr', 'mg')) l
LEFT JOIN competence_traduction ct ON ct.id_competence = s.id AND ct.id_langue = l.id
WHERE ct.id_competence IS NULL;
SELECT ct.libelle AS libelle_fr_duplique, count(*)
FROM competence_traduction ct
JOIN pitikorana_seed_competences s ON s.id = ct.id_competence
JOIN langue l ON l.id = ct.id_langue
WHERE l.code = 'fr'
GROUP BY ct.libelle HAVING count(*) > 1;
SELECT ct.libelle AS libelle_mg_duplique, count(*)
FROM competence_traduction ct
JOIN pitikorana_seed_competences s ON s.id = ct.id_competence
JOIN langue l ON l.id = ct.id_langue
WHERE l.code = 'mg'
GROUP BY ct.libelle HAVING count(*) > 1;
SELECT id AS uuid_source_duplique, count(*)
FROM pitikorana_seed_competences
GROUP BY id HAVING count(*) > 1;
SELECT ct.id_competence AS traduction_orpheline
FROM competence_traduction ct
JOIN pitikorana_seed_competences s ON s.id = ct.id_competence
LEFT JOIN competence c ON c.id = ct.id_competence
WHERE c.id IS NULL;

